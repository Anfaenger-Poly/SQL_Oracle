-- 위의 내용에 인보이스 번호가 짝수인지 홀수인지에 대한 컬럼을 추가하여 표시해 줘!
-- (OUTBOUND_DATE, DY[요일], INVOICE_NO, EVENODD[홀/짝], ORDER_NM)
