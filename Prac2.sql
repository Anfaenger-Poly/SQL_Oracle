-- [브랜드] & [상품]별 주문수량 합계를 표시하되, 상품명은 스칼라쿼리로 표시해 줘
SELECT D.BRAND_CD, D.ITEM_CD
      ,SUM(D.ORDER_QTY) AS SUM_QTY
      ,(SELECT I.ITEM_NM
          FROM A_ITEM I
         WHERE I.BRAND_CD = D.BRAND_CD
