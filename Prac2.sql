-- 출고유형이 M1로 시작하면 상온, M2로 시작하면 저온이라고 표시해 줘
-- (OUTBOUND_DATE, DY[요일], INVOICE_NO, EVENODD[홀/짝], ORDER_NM, TEMP[상온/저온])
SELECT OUTBOUND_DATE
      ,TO_CHAR(OUTBOUND_DATE, 'DY') AS DAY
      ,INVOICE_NO
      ,CASE WHEN MOD(TO_NUMBER(SUBSTR(INVOICE_NO, 2)), 2) = 0 THEN '짝' ELSE '홀' END AS EVENODD
      ,ORDER_NM
      ,CASE WHEN OUT_TYPE_DIV LIKE 'M1%' THEN '상온'
            WHEN OUT_TYPE_DIV LIKE 'M2%' THEN '저온' END AS TEMP
  FROM A_OUT_M;

-- 주문수량이 1~2이면 '하', 3~4이면 '중', 5이상이면 '상’으로 표시해 줘
-- (BRAND_CD, INVOICE_NO, LINE_NO, ITEM_CD, ORDER_QTY, GRADE[상/중/하])
SELECT BRAND_CD, INVOICE_NO, LINE_NO, ITEM_CD, ORDER_QTY
      ,CASE WHEN ORDER_QTY >= 5 THEN '상'
            WHEN ORDER_QTY BETWEEN 3 AND 4 THEN '중'
            ELSE '하'
      END AS GRADE
  FROM A_OUT_D
 ORDER BY CASE WHEN ORDER_QTY >= 5 THEN '상'
               WHEN ORDER_QTY BETWEEN 3 AND 4 THEN '중'
               ELSE '하' END DESC;
            
-- [브랜드] & [상온/저온]별로 몇 개의 인보이스를 처리했는지 가르쳐 줘
SELECT BRAND_CD, COUNT(*) AS INVOICE_CNT
      ,CASE WHEN OUT_TYPE_DIV LIKE 'M1%' THEN '상온'
            WHEN OUT_TYPE_DIV LIKE 'M2%' THEN '저온' END AS TEMP
  FROM A_OUT_M
 GROUP BY BRAND_CD, CASE WHEN OUT_TYPE_DIV LIKE 'M1%' THEN '상온'
                         WHEN OUT_TYPE_DIV LIKE 'M2%' THEN '저온' END;
                         
-- [브랜드] & [상/중/하(인보이스 단위의 합계)]별로 몇 개의 인보이스를 처리했는지 가르쳐 줘
SELECT BRAND_CD
      ,CASE WHEN ORDER_QTY >= 5 THEN '상'
            WHEN ORDER_QTY BETWEEN 3 AND 4 THEN '중'
            ELSE '하' END AS GRADE
      ,COUNT(*) AS INVOICE_CNT 
  FROM A_OUT_D
 GROUP BY BRAND_CD, CASE WHEN ORDER_QTY >= 5 THEN '상'
            WHEN ORDER_QTY BETWEEN 3 AND 4 THEN '중'
            ELSE '하' END;
        
