SELECT *
    FROM A_ITEM;
    
SELECT *
    FROM A_OUT_M;
    
SELECT *
    FROM A_OUT_D;
    
SELECT BRAND_CD, COUNT(DISTINCT INVOICE_NO) AS INVOICE_CNT
FROM A_OUT_M
GROUP BY BRAND_CD;

SELECT SUM(ORDER_QTY) AS TOTAL_QTY
FROM A_OUT_D
WHERE BRAND_CD = 1001 AND ITEM_CD = 'A';

SELECT BRAND_CD, COUNT(*)
    FROM A_OUT_M
    GROUP BY BRAND_CD
    ORDER BY BRAND_CD DESC;
    
SELECT SUM(ORDER_QTY)
    FROM A_OUT_D
    WHERE BRAND_CD = '1001'
    AND ITEM_CD = 'A';
    
SELECT BRAND_CD, ITEM_CD, SUM(ORDER_QTY)
  FROM A_OUT_D
 WHERE (BRAND_CD, INVOICE_NO) IN (
           SELECT BRAND_CD, INVOICE_NO
             FROM A_OUT_M
            WHERE OUTBOUND_DATE = DATE '2023-01-03'
       )
 GROUP BY BRAND_CD, ITEM_CD
 ORDER BY BRAND_CD, ITEM_CD;
 
 SELECT M2.BRAND_CD, M2.ITEM_CD, SUM(M2.ORDER_QTY)
    FROM A_OUT_M M1
        JOIN A_OUT_D M2 ON M2.BRAND_CD = M1.BRAND_CD
                        AND M2.INVOICE_NO = M1.INVOICE_NO
    WHERE M1.OUTBOUND_DATE = '2023-01-03'
    GROUP BY M2.BRAND_CD, M2.ITEM_CD
    ORDER BY M2.BRAND_CD, M2.ITEM_CD;