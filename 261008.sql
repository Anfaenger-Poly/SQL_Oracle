      ,CASE WHEN ROWNUM <= 2 THEN ITEM_CD ELSE 'etc' END AS NEW_ITEM
  FROM (
        SELECT ITEM_CD, SUM(ORDER_QTY) AS SUM_QTY
          FROM A_OUT_D
         GROUP BY ITEM_CD
         ORDER BY SUM_QTY DESC
        )
;

SELECT CASE WHEN ROWNUM <= 2 THEN ITEM_CD ELSE 'etc' END AS NEW_ITEM
