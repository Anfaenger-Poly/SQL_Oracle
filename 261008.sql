SELECT BRAND_CD
     ,CASE WHEN ORDER_QTY BETWEEN 1 AND 2 THEN '하'
           WHEN ORDER_QTY BETWEEN 3 AND 4 THEN '중'
           WHEN ORDER_QTY >= 5            THEN '상'
       END AS GRADE
     ,COUNT(DISTINCT INVOICE_NO) AS INV_CNT
  FROM A_OUT_D
 GROUP BY BRAND_CD
         ,ORDER_QTY
 ORDER BY BRAND_CD, GRADE
;

SELECT BRAND_CD
      ,CASE WHEN SUM_QTY BETWEEN 1 AND 2 THEN '하'
            WHEN SUM_QTY BETWEEN 3 AND 4 THEN '중'
            ELSE '상'
       END  AS GRADE
      ,COUNT(*) AS INV_CNT
  FROM (--1) 브랜드, 인보이스 단위로 주문수량 집계
        SELECT BRAND_CD, INVOICE_NO, SUM(ORDER_QTY) AS SUM_QTY
          FROM A_OUT_D
         GROUP BY BRAND_CD, INVOICE_NO
        )
 GROUP BY BRAND_CD
         ,CASE WHEN SUM_QTY BETWEEN 1 AND 2 THEN '하'
               WHEN SUM_QTY BETWEEN 3 AND 4 THEN '중'
               ELSE '상'
           END
;

