-- 1001 브랜드의 주문내역을 표시하되, C 상품을 가장 먼저 표시하고, 나머지
-- 상품은 상품코드 순으로 나열해 줘.
-- (BRAND_CD, INVOICE_NO, LINE_NO, ITEM_CD, ORDER_QTY, GRADE[상/중/하])
-- 단, 동일한 상품에 대해서는 주문수량이 많은 것부터 나열해 줘
SELECT BRAND_CD, INVOICE_NO, LINE_NO, ITEM_CD, ORDER_QTY
     ,CASE WHEN ORDER_QTY >= 5 THEN '상' 
           WHEN ORDER_QTY >= 3 THEN '중'
           ELSE '하'
       END AS GRADE
  FROM A_OUT_D
 WHERE BRAND_CD = '1001'
 ORDER BY CASE WHEN ITEM_CD = 'C' THEN 0 ELSE 1 END
         ,ITEM_CD
         ,ORDER_QTY DESC;
         
-- 실전문제① ▶ WHERE절, SELECT절에 CASE문 적용하기
SELECT OUTBOUND_DATE
      ,COUNT(INVOICE_NO) AS INOICE_NO
      ,COUNT(CASE WHEN OUT_TYPE_DIV LIKE 'M1%' THEN 1 END) AS M1_CNT
      ,COUNT(CASE WHEN OUT_TYPE_DIV LIKE 'M2%' THEN 1 END) AS M2_CNT
  FROM LO_OUT_M
 WHERE OUTBOUND_DATE BETWEEN '2019-09-01' AND '2019-09-19'
   AND OUT_BOX_DIV LIKE CASE :CONT WHEN '0' THEN '%'
                                   WHEN '1' THEN 'D%'
                                   WHEN '2' THEN 'F%'
                                   ELSE '999'
                         END
 GROUP BY OUTBOUND_DATE
 ORDER BY OUTBOUND_DATE
;

